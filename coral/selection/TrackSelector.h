#ifndef CORAL_TRACK_SELECTOR_H
#define CORAL_TRACK_SELECTOR_H

#include <coral/selection/SelectionCapabilities.h>
#include <coral/selection/TrackGroup.h>
#include <coral/selection/TrackSelectorResult.h>
#include <coral/upstream/BandwidthMeter.h>

#include <memory>

namespace coral {

/**
 * The track info object
 */
class TrackInfo {
public:
  TrackInfo() = default;

  virtual ~TrackInfo() = default;
};

class TrackSelector {
public:
  virtual ~TrackSelector() = default;

  /**
   * Notified when selections previously made by a {@link TrackSelector} are no
   * longer valid.
   */
  class InvalidationListener {
  public:
    virtual ~InvalidationListener() = default;

    /**
     * Called by a {@link TrackSelector} to indicate that selections it has
     * previously made are no longer valid. May be called from any thread.
     */
    virtual void onTrackSelectionsInvalidated() = 0;
  };

  /**
   * Called by the player to initialize the selector.
   *
   * @param listener An invalidation listener that the selector can call to
   * indicate that selections it has previously made are no longer valid.
   * @param bandwidthMeter A bandwidth meter which can be used by track
   * selections to select tracks.
   */
  void init(InvalidationListener* listener,
      const std::shared_ptr<BandwidthMeter>& bandwidthMeter) {
    this->mListener = listener;
    this->mBandwidthMeter = bandwidthMeter;
  }

  /**
   * Called to perform a track selection.
   *
   * @param trackCapabilities The {@link TrackCapabilities} for which tracks are
   * to be selected.
   * @param trackGroups The available track groups.
   * @return A {@link TrackSelectorResult} describing the track selections.
   */
  virtual std::shared_ptr<TrackSelectorResult>
  selectTracks(const std::vector<std::shared_ptr<SelectionCapabilities>>& rendererCapabilities,
      const std::shared_ptr<TrackGroupArray>& trackGroups) = 0;

  /**
   * Called by the player when a {@link TrackSelectorResult} previously
   * generated by {@link #selectTracks(SelectionCapabilities[], TrackGroupArray)}
   * is activated.
   *
   * @param info The value of {@link TrackSelectorResult#info} in the activated
   * selection.
   */
  virtual void onSelectionActivated(const std::shared_ptr<TrackInfo>& info) = 0;

  /**
   * Returns a bandwidth meter which can be used by track selections to select
   * tracks. Must only be called after {@link #init(InvalidationListener,
   * BandwidthMeter)} has been called.
   */
  const std::shared_ptr<BandwidthMeter>& getBandwidthMeter() const {
    return mBandwidthMeter;
  }

protected:
  /**
   * Calls {@link InvalidationListener#onTrackSelectionsInvalidated()} to
   * invalidate all previously generated track selections.
   */
  void invalidate() {
    if (mListener != nullptr) {
      mListener->onTrackSelectionsInvalidated();
    }
  }

private:
  /**
   * The listener the selector tells when its selections are no longer valid, or null.
   *
   * <p>It is initialised here: a selector that is never {@link #init}ialised - which is what a
   * selector built directly by an application is - would otherwise compare and call an indeterminate
   * pointer the first time its parameters change.
   */
  InvalidationListener* mListener = nullptr;
  std::shared_ptr<BandwidthMeter> mBandwidthMeter;
};

} // namespace coral

#endif // CORAL_TRACK_SELECTOR_H
